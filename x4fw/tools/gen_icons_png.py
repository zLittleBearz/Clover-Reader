#!/usr/bin/env python3
# สร้าง icons.h จากไฟล์ PNG ต้นฉบับโดยตรง (ไม่วาดใหม่): ย่อเป็น 64x64 แล้ว threshold เป็น 1 บิต
# ปรับน้ำหนักเส้นของแต่ละไอคอนให้เท่ากันก่อนย่อ (กัดขอบเข้าเล็กน้อยกับไอคอนที่เส้นหนากว่า)
# ใช้: python3 tools/gen_icons_png.py [โฟลเดอร์_png=tools/icon_src] [out=icons.h] [preview.png]
import sys, os
import numpy as np
from PIL import Image
from scipy.ndimage import distance_transform_edt, binary_erosion

SRC = sys.argv[1] if len(sys.argv) > 1 else 'tools/icon_src'
OUT = sys.argv[2] if len(sys.argv) > 2 else 'icons.h'
PREV = sys.argv[3] if len(sys.argv) > 3 else None
N = 64
FIT = 60            # ไอคอนที่ใหญ่สุดยาวไม่เกินนี้ (พิกเซลจริง)
# ชื่อตัวแปรใน firmware -> ไฟล์ต้นฉบับ  (ICON_APPS คือไอคอน "more")
ICONS = [('LIBRARY', 'library.png'), ('APPS', 'more.png'), ('UPDATE', 'update.png'), ('SETTING', 'setting.png')]

def load(fn):
    a = np.array(Image.open(os.path.join(SRC, fn)).convert('L')) < 128
    ys, xs = np.where(a)
    return a[ys.min():ys.max() + 1, xs.min():xs.max() + 1]

def stroke(a):
    per = (a & ~binary_erosion(a)).sum()
    return 2.0 * a.sum() / per

srcs = {n: load(f) for n, f in ICONS}
strokes = {n: stroke(a) for n, a in srcs.items()}
scale = FIT / max(max(a.shape) for a in srcs.values())     # ตัวคูณเดียวกันทุกไอคอน
target = min(strokes.values())                             # ปรับให้เส้นเท่ากับไอคอนที่บางสุด

def to_bits(name):
    a = srcs[name]
    r = (strokes[name] - target) / 2.0                     # กัดเข้าด้านละ r พิกเซลต้นฉบับ
    if r > 0.3:
        pad = np.pad(a, 4)
        a = (distance_transform_edt(pad) > r)[4:-4, 4:-4]
    h, w = a.shape
    nw, nh = max(1, round(w * scale)), max(1, round(h * scale))
    im = Image.fromarray((a * 255).astype('uint8')).resize((nw, nh), Image.BOX)
    can = Image.new('L', (N, N), 0)
    can.paste(im, ((N - nw) // 2, (N - nh) // 2))
    m = np.array(can) >= 128
    bits = []
    for y in range(N):
        for xb in range(N // 8):
            v = 0
            for k in range(8): v = (v << 1) | int(m[y, xb * 8 + k])
            bits.append(v)
    return bits, m

lines = ['// 64x64 1-bit icons, MSB first, 1 = black (generated by tools/gen_icons_png.py from tools/icon_src/*.png)', '#pragma once', '#include <stdint.h>']
tiles = []
for name, _ in ICONS:
    bits, m = to_bits(name); tiles.append(m)
    lines.append('static const uint8_t ICON_%s[512] = {' % name)
    for i in range(0, 512, 16): lines.append('  ' + ','.join('0x%02X' % b for b in bits[i:i + 16]) + ',')
    lines.append('};')
open(OUT, 'w').write('\n'.join(lines) + '\n')
if PREV:
    sheet = Image.new('L', (len(tiles) * 280, 272), 255)
    for i, m in enumerate(tiles):
        t = Image.fromarray((~m * 255).astype('uint8')).resize((256, 256), Image.NEAREST)
        sheet.paste(t, (i * 280 + 8, 8))
    sheet.save(PREV)
print('wrote', OUT, {k: round(v, 1) for k, v in strokes.items()}, 'scale=%.3f' % scale)
