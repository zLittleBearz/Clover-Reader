#!/usr/bin/env python3
# สร้าง icons.h : ไอคอน 64x64 1bpp เส้นหนาคงที่ (วาดที่ 8 เท่า -> ย่อ -> threshold)
# ใช้: python3 tools/gen_icons.py [out_icons.h] [preview.png]
import sys, math
import numpy as np
from PIL import Image, ImageDraw
from scipy.ndimage import distance_transform_edt

N = 64          # ขนาดไอคอนจริง
S = 8           # ซูเปอร์แซมป์
W = 4           # ความหนาเส้น (พิกเซลจริง) ปรับตรงนี้จุดเดียว
R = N * S

def canvas(): return Image.new('L', (R, R), 0)
def sc(p): return [(x * S, y * S) for x, y in p]

def outline(mask_img, w=W):
    """เส้นขอบด้านในของรูปทึบ หนา w พิกเซลจริง เท่ากันทุกจุด"""
    m = np.array(mask_img) > 127
    d = distance_transform_edt(m)
    return m & (d <= w * S)

def rrect(box, r):
    im = canvas(); d = ImageDraw.Draw(im)
    x0, y0, x1, y1 = [v * S for v in box]
    d.rounded_rectangle((x0, y0, x1, y1), r * S, fill=255)
    return im

def poly(pts):
    im = canvas(); ImageDraw.Draw(im).polygon(sc(pts), fill=255); return im

def line(d, pts, w=W):
    p = sc(pts); d.line(p, fill=255, width=int(w * S), joint='curve')
    for x, y in p:
        r = w * S / 2; d.ellipse((x - r, y - r, x + r, y + r), fill=255)

def to_img(boolarr):
    return Image.fromarray((boolarr * 255).astype('uint8'))

def merge(*arrs):
    o = np.zeros((R, R), bool)
    for a in arrs: o |= a
    return o

def rot(pts, cx, cy, deg):
    a = math.radians(deg); c, s = math.cos(a), math.sin(a)
    return [(cx + (x - cx) * c - (y - cy) * s, cy + (x - cx) * s + (y - cy) * c) for x, y in pts]

def icon_library():
    parts = []
    parts.append(outline(rrect((5, 14, 19, 58), 2)))
    parts.append(outline(rrect((24, 6, 38, 58), 2)))
    b = [(42, 18), (54, 18), (54, 58), (42, 58)]
    b = rot(b, 48, 58, 12)
    parts.append(outline(poly(b)))
    # เส้นแบ่งสันหนังสือเล่มกลาง
    im = canvas(); d = ImageDraw.Draw(im)
    line(d, [(24, 18), (38, 18)])
    parts.append(np.array(im) > 127)
    return merge(*parts)

def icon_setting():
    cx = cy = 32
    pts = []
    teeth = 8
    ro, ri = 29.5, 22
    for i in range(teeth):
        a0 = 2 * math.pi * i / teeth
        step = 2 * math.pi / teeth
        for t, r in ((-0.20, ri), (-0.12, ro), (0.12, ro), (0.20, ri)):
            a = a0 + t * step * 2.0
            pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    gear = poly(pts)
    # เจาะรูกลาง แล้วเส้นขอบรอบรูหนา W เท่ากัน
    g = np.array(gear) > 127
    yy, xx = np.ogrid[:R, :R]
    hole_r = 10 * S
    hole = (xx - cx * S) ** 2 + (yy - cy * S) ** 2 <= hole_r ** 2
    g2 = g & ~hole
    # ขอบนอก+ขอบในของวงแหวนเกียร์: ใช้ระยะจากพื้นที่ว่างทั้งสองด้าน
    d = distance_transform_edt(g2)
    return g2 & (d <= W * S)

def icon_apps():
    parts = []
    for bx in (5, 35):
        for by in (5, 35):
            parts.append(outline(rrect((bx, by, bx + 24, by + 24), 5)))
    return merge(*parts)

def icon_update():
    # เมฆ = วงกลม 3 วง + แท่งฐาน รวมเป็นรูปทึบแล้วเอาเส้นขอบ
    im = canvas(); d = ImageDraw.Draw(im)
    def circ(cx, cy, r): d.ellipse(((cx - r) * S, (cy - r) * S, (cx + r) * S, (cy + r) * S), fill=255)
    circ(16, 40, 11); circ(30, 26, 15); circ(47, 36, 13)
    d.rectangle((16 * S, 36 * S, 47 * S, 51 * S), fill=255)
    cloud = outline(im)
    # ลูกศรขึ้น กลางเมฆ
    im2 = canvas(); d2 = ImageDraw.Draw(im2)
    line(d2, [(32, 46), (32, 30)])
    line(d2, [(23, 38), (32, 29), (41, 38)])
    # เคลียร์เส้นเมฆส่วนฐานที่ทับลูกศร: ลูกศรอยู่ในเมฆ ไม่ชนฐาน (ฐานล่างสุด y~51)
    return merge(cloud, np.array(im2) > 127)

ICONS = [('LIBRARY', icon_library), ('SETTING', icon_setting), ('APPS', icon_apps), ('UPDATE', icon_update)]

def to_bits(arr):
    im = to_img(arr).resize((N, N), Image.BOX)       # เฉลี่ยแล้ว threshold
    a = np.array(im) >= 110
    out = []
    for y in range(N):
        for xb in range(N // 8):
            v = 0
            for k in range(8):
                v = (v << 1) | int(a[y, xb * 8 + k])
            out.append(v)
    return out, a

def main():
    out = sys.argv[1] if len(sys.argv) > 1 else 'icons.h'
    prev = sys.argv[2] if len(sys.argv) > 2 else None
    lines = ['// 64x64 1-bit icons, MSB first, 1 = black (generated by tools/gen_icons.py, stroke=%dpx)' % W,
             '#pragma once', '#include <stdint.h>']
    tiles = []
    for name, fn in ICONS:
        bits, a = to_bits(fn())
        tiles.append(a)
        lines.append('static const uint8_t ICON_%s[512] = {' % name)
        for i in range(0, 512, 16):
            lines.append('  ' + ','.join('0x%02X' % b for b in bits[i:i + 16]) + ',')
        lines.append('};')
    open(out, 'w').write('\n'.join(lines) + '\n')
    if prev:
        sheet = Image.new('L', (len(tiles) * 280, 272), 255)
        for i, a in enumerate(tiles):
            t = Image.fromarray((~a * 255).astype('uint8')).resize((256, 256), Image.NEAREST)
            sheet.paste(t, (i * 280 + 8, 8))
        sheet.save(prev)
    print('wrote', out)

main()
